import type { DataStore, Loader, LoaderContext } from 'astro/loaders';
import { pageSchema } from 'fumadocs-core/source/schema';
import { z } from 'zod';

/**
 * Publication rules for the MDX pages under `content/`.
 *
 * A page is published only when its frontmatter says `status: published`;
 * anything else, including a missing field, is a draft. Two gates read that:
 *
 * - Astro/Fumapress: `publishedOnly()` drops drafts before they enter the
 *   content store, so they never reach a route or the page tree.
 * - Docs7: `renderDocs7Ignore()` renders `content/.docs7ignore`, the list of
 *   drafts that Docs7 must not upload (`pnpm docs7:ignore`).
 *
 * This module is pure: no I/O, no clock, no environment reads.
 */

export const PAGE_STATUSES = ['draft', 'published'] as const;

export type PageStatus = (typeof PAGE_STATUSES)[number];

export const pageStatusSchema = z.enum(PAGE_STATUSES).default('draft');

/** Page frontmatter, including the field both publication gates read. */
export const pageFrontmatterSchema = pageSchema.extend({ status: pageStatusSchema });

/**
 * Validates a frontmatter status. The generator uses this so that a typo fails
 * instead of silently unpublishing a page.
 */
export function parsePageStatus(value: unknown): PageStatus {
  return pageStatusSchema.parse(value);
}

/** The raw `status` field of a frontmatter object, if the object has one. */
export function pageStatusOf(data: unknown): unknown {
  return typeof data === 'object' && data !== null
    ? (data as { status?: unknown }).status
    : undefined;
}

/** True only for the exact value `published`; unknown or missing means draft. */
export function isPublished(data: unknown): boolean {
  const status = pageStatusSchema.safeParse(pageStatusOf(data));
  return status.success && status.data === 'published';
}

export interface ContentPageRef {
  /** Content-root-relative MDX path, for example `blog/hello.mdx`. */
  path: string;
  data: unknown;
}

/** Content paths of the pages whose status is not `published`. */
export function draftPaths(entries: readonly ContentPageRef[]): string[] {
  return entries
    .filter((entry) => !isPublished(entry.data))
    .map((entry) => entry.path);
}

const DOCS7_IGNORE_HEADER = [
  '# Generated by `pnpm docs7:ignore`; do not edit by hand.',
  '# Pages whose frontmatter status is not "published" are not uploaded to Docs7.',
];

/**
 * `content/.docs7ignore` contents: a fixed header and the sorted, unique paths
 * (content-root relative) that Docs7 must leave out of the upload.
 */
export function renderDocs7Ignore(paths: readonly string[]): string {
  const unique = [...new Set(paths.map((path) => path.replaceAll('\\', '/')))].sort();
  return [...DOCS7_IGNORE_HEADER, ...unique].join('\n') + '\n';
}

/**
 * A page path or docs.json page reference without its extension or a trailing
 * slash, so `index` matches `index.mdx` and `en/index` matches `en/index.mdx`.
 *
 * `index` is deliberately not folded into its directory: Docs7 lists the root
 * page as `index` and the English root page as `en/index`, and `en/` separates
 * languages, so dropping `/index` would turn the former into an empty path and
 * the latter into a language directory that no page occupies.
 */
function pageKey(value: string): string {
  return value
    .replaceAll('\\', '/')
    .replace(/^\.?\//, '')
    .replace(/\/+$/, '')
    .replace(/\.(?:md|mdx)$/i, '');
}

/**
 * docs.json navigation entries that point at a draft page. Navigation does not
 * gate publication in Docs7 (any uploaded MDX is served by path), so a draft
 * that stays in the navigation would become a 404 page; the generator fails.
 */
export function draftNavigationConflicts(
  navPages: readonly string[],
  draft: readonly string[],
): string[] {
  const drafts = new Set(draft.map(pageKey));
  return navPages.filter((page) => drafts.has(pageKey(page)));
}

/**
 * Wraps a page loader so the content store never receives a draft entry.
 * Astro reads entries, routes, and the page tree from that store.
 *
 * The loader's own schema is kept, so a collection that does not set one still
 * validates page frontmatter.
 */
export function publishedOnly(loader: Loader): Loader {
  const schema = 'schema' in loader ? { schema: loader.schema } : {};
  return {
    ...schema,
    name: `${loader.name}:published-only`,
    async load(context: LoaderContext): Promise<void> {
      await loader.load({ ...context, store: withoutDrafts(context.store) });
    },
  };
}

type StoreEntry = Parameters<DataStore['set']>[0];

/**
 * Proxies a data store and drops `set` calls for pages that are not published.
 * Every other method is delegated as-is.
 */
function withoutDrafts(store: DataStore): DataStore {
  return new Proxy(store, {
    get(target, key) {
      if (key === 'set') {
        return (entry: StoreEntry): boolean => {
          if (!isPublished(entry.data)) {
            // A page that becomes a draft deletes its previous entry; skipping
            // the write alone would leave the published copy in the store.
            target.delete(entry.id);
            return false;
          }
          return target.set(entry);
        };
      }
      const value = Reflect.get(target, key, target);
      return typeof value === 'function' ? value.bind(target) : value;
    },
  });
}
