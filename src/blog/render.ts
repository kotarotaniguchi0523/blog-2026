import { z } from 'zod';

import { isPublished, pageStatusSchema } from '../content/publication.ts';

/**
 * The Blog index is generated from the posts under `content/blog/` and
 * `content/en/blog/`, the same way the Scrap index is generated from the
 * published GitHub threads.
 */

export type BlogLanguage = 'ja' | 'en';

export const BLOG_GENERATED_MARKER = '{/* generated by pnpm blog:index; do not edit */}';

const SLUG_PATTERN = /^[A-Za-z0-9_-]+$/;
const DATE_PATTERN = /^\d{4}-\d{2}-\d{2}$/;

const blogPostFrontmatterSchema = z.object({
  title: z.string().trim().min(1),
  date: z.string().regex(DATE_PATTERN, 'expected YYYY-MM-DD').optional(),
  status: pageStatusSchema,
});

export interface BlogPost {
  /** File name without the extension. Used as the URL segment. */
  slug: string;
  title: string;
  date?: string;
}

const LABELS = {
  ja: {
    title: 'Blog',
    description: 'merino の記事',
    empty: 'まだ記事はありません。',
    basePath: '/blog',
  },
  en: {
    title: 'Blog',
    description: 'Articles by merino',
    empty: 'No posts yet.',
    basePath: '/en/blog',
  },
} as const;

/**
 * Validates one post and returns it, or `null` for a draft.
 *
 * `path` is content-root relative, for example `blog/hello.mdx` or
 * `en/blog/hello.mdx`. Nested directories are rejected so that one post maps
 * to one `/blog/<slug>` page.
 */
export function parseBlogPost(
  path: string,
  data: unknown,
  language: BlogLanguage,
): BlogPost | null {
  const directory = language === 'en' ? 'en/blog/' : 'blog/';
  if (!path.startsWith(directory)) {
    throw new Error(`Blog post ${path} is not under content/${directory}`);
  }
  const file = path.slice(directory.length);
  if (!file.endsWith('.mdx') || file.includes('/')) {
    throw new Error(`Blog post ${path} must be a direct .mdx file under content/${directory}`);
  }
  const slug = file.slice(0, -'.mdx'.length);
  if (!SLUG_PATTERN.test(slug)) {
    throw new Error(`Blog post ${path} has a slug that is not URL-safe: ${slug}`);
  }

  const parsed = blogPostFrontmatterSchema.safeParse(data);
  if (!parsed.success) {
    const issue = parsed.error.issues[0];
    const field = issue?.path.join('.') || 'frontmatter';
    throw new Error(`Blog post ${path} has invalid ${field}: ${issue?.message ?? 'unknown error'}`);
  }
  if (!isPublished(data)) return null;

  return {
    slug,
    title: parsed.data.title,
    ...(parsed.data.date === undefined ? {} : { date: parsed.data.date }),
  };
}

export function renderBlogIndex(posts: readonly BlogPost[], language: BlogLanguage): string {
  const labels = LABELS[language];
  const sorted = [...posts].sort((left, right) => {
    if (left.date !== right.date) {
      if (left.date === undefined) return 1;
      if (right.date === undefined) return -1;
      return right.date.localeCompare(left.date);
    }
    return left.slug.localeCompare(right.slug);
  });
  const lines = [
    '---',
    `title: ${JSON.stringify(labels.title)}`,
    `description: ${JSON.stringify(labels.description)}`,
    'icon: newspaper',
    'status: published',
    '---',
    '',
    BLOG_GENERATED_MARKER,
    '',
  ];

  if (sorted.length === 0) {
    lines.push(labels.empty, '');
    return lines.join('\n');
  }

  for (const post of sorted) {
    const date = post.date === undefined ? '' : ` — ${post.date}`;
    lines.push(`- [${escapeLinkText(post.title)}](${labels.basePath}/${post.slug})${date}`);
  }
  lines.push('');
  return lines.join('\n');
}

function escapeLinkText(value: string): string {
  return value
    .replaceAll('\\', '\\\\')
    .replaceAll('[', '\\[')
    .replaceAll(']', '\\]')
    .replaceAll(/\s*\n\s*/g, ' ');
}
