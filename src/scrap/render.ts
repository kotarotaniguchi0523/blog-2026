import type { ScrapSnapshot } from './publication.ts';

type ScrapLanguage = 'ja' | 'en';

export interface ScrapRenderContext {
  owner: string;
  repo: string;
  language: ScrapLanguage;
}

/** Marks files owned by the sync job so stale pages can be removed safely. */
export const GENERATED_MARKER = '{/* generated by pnpm scrap:sync; do not edit */}';

const LABELS = {
  ja: {
    title: 'Scrap',
    description: 'Notes and learnings by merino',
    empty: 'まだ Scrap はありません。',
    basePath: '/scraps',
    author: '作者',
    createdAt: '作成日',
    state: '状態',
    viewOnGitHub: 'GitHub で見る',
    comments: 'コメント',
    noComments: 'コメントはまだありません。',
    noBody: '本文はありません。',
    unknown: '不明',
    open: 'オープン',
    closed: 'クローズ',
    by: '作者',
  },
  en: {
    title: 'Scrap',
    description: 'Notes and learnings by merino',
    empty: 'No scraps yet.',
    basePath: '/en/scraps',
    author: 'Author',
    createdAt: 'Created',
    state: 'State',
    viewOnGitHub: 'View on GitHub',
    comments: 'Comments',
    noComments: 'No comments yet.',
    noBody: 'No body.',
    unknown: 'unknown',
    open: 'Open',
    closed: 'Closed',
    by: 'by',
  },
} as const;

export function scrapSlug(id: string): string {
  // GitHub node IDs are URL-safe in practice. Reject anything else instead of
  // writing a path traversal or a percent-encoded slash into the content tree.
  if (!/^[A-Za-z0-9_-]+$/.test(id)) {
    throw new TypeError(`Scrap ID is not URL-safe: ${id}`);
  }
  return encodeURIComponent(id);
}

export function renderScrapIndex(
  snapshots: readonly ScrapSnapshot[],
  context: ScrapRenderContext,
): string {
  const labels = LABELS[context.language];
  const sorted = [...snapshots].sort(
    (left, right) =>
      right.createdAt.localeCompare(left.createdAt)
      || right.issueNumber - left.issueNumber,
  );
  const lines = [
    '---',
    `title: ${yamlString(labels.title)}`,
    `description: ${yamlString(labels.description)}`,
    'icon: messages-square',
    'status: published',
    '---',
    '',
    GENERATED_MARKER,
    '',
  ];

  if (sorted.length === 0) {
    lines.push(labels.empty, '');
    return lines.join('\n');
  }

  for (const snapshot of sorted) {
    const href = `${labels.basePath}/${scrapSlug(snapshot.id)}`;
    const meta = [
      formatAuthor(snapshot.author, labels.unknown),
      formatDate(snapshot.createdAt),
      snapshot.state === 'open' ? labels.open : labels.closed,
      commentCount(snapshot.comments.length, context.language),
    ].join(' · ');
    lines.push(`- [${escapeLinkText(snapshot.title)}](${href}) — ${meta}`);
  }
  lines.push('');
  return lines.join('\n');
}

export function renderScrapPage(
  snapshot: ScrapSnapshot,
  context: ScrapRenderContext,
): string {
  const labels = LABELS[context.language];
  const issueUrl = `https://github.com/${context.owner}/${context.repo}/issues/${snapshot.issueNumber}`;
  const author = formatAuthor(snapshot.author, labels.unknown);
  const description = snapshot.author === null
    ? labels.title
    : `${labels.title} ${labels.by} ${snapshot.author}`;
  const lines = [
    '---',
    `title: ${yamlString(snapshot.title)}`,
    `description: ${yamlString(description)}`,
    'icon: messages-square',
    'status: published',
    '---',
    '',
    GENERATED_MARKER,
    '',
    `[${labels.viewOnGitHub}](${issueUrl})`,
    '',
    `- ${labels.author}: ${author}`,
    `- ${labels.createdAt}: ${formatDate(snapshot.createdAt)}`,
    `- ${labels.state}: ${snapshot.state === 'open' ? labels.open : labels.closed}`,
    '',
    snapshot.body.trim() === '' ? labels.noBody : snapshot.body.trim(),
    '',
    `## ${labels.comments}`,
    '',
  ];

  if (snapshot.comments.length === 0) {
    lines.push(labels.noComments, '');
    return lines.join('\n');
  }

  for (const comment of snapshot.comments) {
    lines.push(
      `### ${formatAuthor(comment.author, labels.unknown)} · ${formatDate(comment.createdAt)}`,
      '',
      comment.body.trim() === '' ? labels.noBody : comment.body.trim(),
      '',
    );
  }
  return lines.join('\n');
}

function yamlString(value: string): string {
  return JSON.stringify(value);
}

function formatAuthor(login: string | null, unknown: string): string {
  if (login === null) return unknown;
  return `[@${login}](https://github.com/${encodeURIComponent(login)})`;
}

function formatDate(value: string): string {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return value;
  return date.toISOString().slice(0, 10);
}

function commentCount(count: number, language: ScrapLanguage): string {
  if (language === 'ja') return `${count} 件のコメント`;
  return count === 1 ? '1 comment' : `${count} comments`;
}

function escapeLinkText(value: string): string {
  return value
    .replaceAll('\\', '\\\\')
    .replaceAll('[', '\\[')
    .replaceAll(']', '\\]')
    .replaceAll(/\s*\n\s*/g, ' ');
}
